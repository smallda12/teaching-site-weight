/* ==========================================================
   重量教學網 — 版本設定
   ----------------------------------------------------------
   模式說明：
     "auto"   → 本機雙擊開啟(file://) 判為「教室版」，
                架在網路上(http/https) 判為「公開版」
     "教室版" → 點名區可上傳學生照片（資料只存在這台電腦）
     "公開版" → 關閉照片上傳，只用文字輸入姓名
   要強制指定版本，把下面的 模式 改成 "教室版" 或 "公開版"
   ========================================================== */
window.CONFIG = (function () {
  const 模式 = "auto";

  const isFile = location.protocol === "file:";
  const 版本 = 模式 === "auto" ? (isFile ? "教室版" : "公開版") : 模式;

  return {
    版本,
    允許上傳照片: 版本 === "教室版",
    // 換掉 assets/pdf 或影片等檔案後，把這個數字加 1，
    // 否則瀏覽器會繼續開快取裡的舊 PDF（檔名沒變，瀏覽器不會自己去抓新的）
    // 2 = 2026-08-04 深化頁 P40～P54 重生成米色紙雕風（頁圖、圖卡、影片一起換）
    資源版本: 4,
    語音: {
      // 預產語音資料夾（edge-tts / zh-TW-HsiaoChenNeural 女聲，語速 -5%）
      路徑: "assets/audio/",
      // 重新產過語音後，把這個數字加 1，否則瀏覽器會繼續播快取裡的舊音檔
      版本: 2,
      // 瀏覽器即時語音（唸學生姓名、計時器說明等動態文字）
      語系: "zh-TW",
      語速: 0.95,   // 1 為原速，調小變慢
    },
  };
})();
